#!/usr/bin/env python3
"""Identify a coherent generated edition. Run only after build and checks pass."""
from pathlib import Path
import json,hashlib,datetime
R=Path(__file__).resolve().parents[1]
load=lambda p:json.loads(p.read_text())
v=load(R/'data/validation.json');checks=load(R/'data/EDITION_CHECKS.json')
if v['errors'] or not checks['passed']:raise SystemExit('Refusing manifest: edition checks are not passing')
paths=[]
for pre in v['completed_contributions']:
 paths += [R/'contributions'/pre/f for f in ['cases.json','sources.json','claims.json','graph.json','comparisons.json','report.md','questions.md']]
paths.append(R/'contributions/SYN/synthesis_specs.json')
paths += list((R/'analysis').glob('*.md'))+list((R/'analysis').glob('*.json'))
paths += [p for p in (R/'data').iterdir() if p.is_file() and p.suffix in ['.json','.csv','.md'] and p.name not in ['GENERATION_MANIFEST.json']]
paths += list((R/'cases').glob('*.md'))+list((R/'tools').glob('*.py'))
paths += [R/f for f in ['README.md','CHARTER.md','METHODS.md','METHODS_ADDENDUM_V2.md','PLAN.md','index.html']]
paths += [R/'tools/README.md',R/'reviews/EDITION_ACCEPTANCE.md',R/'reviews/RESPONSE_LOG.md',R/'reviews/round2/FINAL_DELTA.json']
files={str(p.relative_to(R)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(set(paths))}
gid=hashlib.sha256(json.dumps(files,sort_keys=True).encode()).hexdigest()
output=dict(generation_id=gid,created_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),counts=v['counts'],files=files,limits='Identifies canonical, narrative, tooling and generated bytes after checks. Independent review targets and subsequent accepted deltas remain separately documented in reviews/.')
(R/'data/GENERATION_MANIFEST.json').write_text(json.dumps(output,indent=2)+'\n')
print(json.dumps(dict(generation_id=gid,files=len(files),counts=v['counts'])))
